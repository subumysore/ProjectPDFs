// ONE string catalogue for every surface: the browser extension, the desktop executable, and the
// marketing/install site. They already share a fill engine; sharing the words too is what keeps a
// user in their own language everywhere instead of only in the parts someone remembered to
// translate.
//
// Why a checked-in catalogue rather than translating at runtime: translation output must be
// deterministic and reviewable. A UI that re-translates itself on every launch can change wording
// between sessions and can fail with no network. These strings are data — a new language is a new
// entry in `STRINGS`, no code change anywhere.
//
// Kept deliberately SHORT and free of embedded markup so a translation cannot break layout, and so
// adding a language stays a job of an hour rather than a week.
//
// This is the UI language. It is separate from, and does not change, two things:
//   • the FORM's language — a filled form always keeps the language it was printed in;
//   • the user's VAULT keys and values — those keep whatever script the user typed them in.


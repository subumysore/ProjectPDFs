/** Every language that has a catalogue (English plus each translation). */
export const AVAILABLE = Object.keys(STRINGS);

/**
 * Translate `key` into `lang`, substituting `{name}` placeholders from `vars`.
 * Falls back to English for a key a translation hasn't got yet — visible English is far better
 * than a blank button, and `i18n.test.mjs` fails the build if that fallback is ever needed.
 */
export function t(lang, key, vars = null) {
  const table = STRINGS[lang] || STRINGS.en;
  let s = table[key];
  if (s === undefined) s = STRINGS.en[key];
  if (s === undefined) return key; // unknown key: show the key rather than nothing
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split("{" + k + "}").join(String(v));
  return s;
}

/** A `t` bound to one language — `const tr = translator("ja"); tr("fill.page")`. */
export function translator(lang) {
  return (key, vars) => t(lang, key, vars);
}

/**
 * Best UI language for a new user, BEFORE they have chosen: the browser/OS languages in
 * preference order, matched to what we have (exact, then the base language of "pt-BR").
 * Returns "en" when nothing matches. The user's explicit choice always overrides this.
 */
export function detectUiLang(preferred = []) {
  for (const raw of preferred) {
    const tag = String(raw || "").toLowerCase();
    if (STRINGS[tag]) return tag;
    const base = tag.split("-")[0];
    if (STRINGS[base]) return base;
  }
  return "en";
}

